export const featuredBooks = books.filter((b) => b.featured);

export const getBooksByCategory = (categorySlug: string): Book[] => {
  if (categorySlug === 'all' || categorySlug === '') return books;
  return books.filter((b) => b.categorySlug === categorySlug);
};

export const searchBooks = (query: string): Book[] => {
  const q = query.toLowerCase().trim();
  if (!q) return books;
  return books.filter(
    (b) =>
      b.title.toLowerCase().includes(q) ||
      b.author.toLowerCase().includes(q) ||
      b.category.toLowerCase().includes(q) ||
      b.isbn.includes(q) ||
      b.tags.some((t) => t.toLowerCase().includes(q)),
  );
};

export const sortBooks = (bookList: Book[], sortBy: string): Book[] => {
  const sorted = [...bookList];
  switch (sortBy) {
    case 'popular':
      return sorted.sort((a, b) => b.downloads - a.downloads);
    case 'rating':
      return sorted.sort((a, b) => b.rating - a.rating);
    case 'az':
      return sorted.sort((a, b) => a.title.localeCompare(b.title));
    case 'newest':
    default:
      return sorted.sort((a, b) => b.year - a.year);
  }
};
